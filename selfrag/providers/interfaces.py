"""Provider interfaces. Stage packages depend on these, never on a vendor SDK."""
from dataclasses import dataclass
from typing import Protocol, Sequence

from selfrag.models import Chunk, Document, Filter


@dataclass(frozen=True)
class Completion:
    text: str
    logprobs: list[float] | None = None                 # per output token
    top_logprobs: list[dict[str, float]] | None = None  # per output token: token -> logprob
    input_tokens: int = 0
    output_tokens: int = 0


class LLMClient(Protocol):
    async def complete(self, prompt: str, *, max_tokens: int, temperature: float = 0.0,
                       stop: list[str] | None = None, logprobs: bool = False,
                       top_logprobs: int = 0) -> Completion: ...
    @property
    def supports_logprobs(self) -> bool: ...


class Embedder(Protocol):
    @property
    def dimension(self) -> int: ...
    def count_tokens(self, text: str) -> int: ...
    async def embed_documents(self, texts: Sequence[str]) -> list[list[float]]: ...
    async def embed_query(self, text: str) -> list[float]: ...


class VectorStore(Protocol):
    async def upsert(self, chunks: Sequence[Chunk], vectors: Sequence[list[float]]) -> None: ...
    async def delete(self, chunk_ids: Sequence[str]) -> None: ...
    async def search(self, vector: list[float], k: int, filters: Filter) -> list[str]: ...


class SparseIndex(Protocol):
    async def upsert(self, chunks: Sequence[Chunk]) -> None: ...
    async def delete(self, chunk_ids: Sequence[str]) -> None: ...
    async def search(self, query: str, k: int, filters: Filter) -> list[str]: ...


class DocStore(Protocol):
    async def get_many(self, ids: Sequence[str]) -> list[Chunk]: ...
    async def document_status(self, doc_id: str) -> str | None: ...
    async def chunk_ids(self, doc_id: str) -> set[str]: ...
    async def begin_ingest(self, doc: Document, chunks: Sequence[Chunk]) -> None: ...
    async def delete_chunks(self, chunk_ids: Sequence[str]) -> None: ...
    async def set_status(self, doc_id: str, status: str) -> None: ...


class Reranker(Protocol):
    async def rerank(self, query: str, chunks: Sequence[Chunk],
                     top_n: int) -> list[tuple[Chunk, float]]: ...
